// Runs automatically before every build (npm "prebuild").
// Photos added to src/assets/ straight from a phone or camera are often
// 4000+ px and several MB. This script, in place:
//   - rotates them upright (EXIF orientation),
//   - shrinks anything larger than 2000 px on its long edge,
//   - re-compresses heavy files,
//   - removes hidden metadata, including GPS location (privacy).
// Already-optimized files are left untouched, so running it again changes nothing.
import sharp from 'sharp';
import { readdir, readFile, writeFile } from 'node:fs/promises';
import { join, extname } from 'node:path';

// Work from in-memory buffers: on Windows, sharp's file cache would keep the
// file open and block overwriting it.
sharp.cache(false);

const ROOT = 'src/assets';
const MAX_EDGE = 2000;
const MAX_BYTES = 900 * 1024; // re-compress files heavier than ~0.9 MB
const EXTS = new Set(['.jpg', '.jpeg', '.png', '.webp']);

async function* walk(dir) {
  for (const entry of await readdir(dir, { withFileTypes: true })) {
    const full = join(dir, entry.name);
    if (entry.isDirectory()) yield* walk(full);
    else if (EXTS.has(extname(entry.name).toLowerCase())) yield full;
  }
}

const kb = (n) => `${Math.round(n / 1024)} KB`;
let changed = 0;

for await (const file of walk(ROOT)) {
  // The brand logo is generated by scripts/generate-icons.mjs and kept lossless.
  if (file.includes(join('assets', 'brand'))) continue;

  const input = await readFile(file);
  const size = input.length;
  const meta = await sharp(input).metadata();
  const tooBig = Math.max(meta.width ?? 0, meta.height ?? 0) > MAX_EDGE;
  const tooHeavy = size > MAX_BYTES;
  const hasMetadata = Boolean(meta.exif || meta.xmp || meta.iptc);
  if (!tooBig && !tooHeavy && !hasMetadata) continue;

  let pipeline = sharp(input).rotate(); // apply EXIF orientation, then drop metadata
  if (tooBig) {
    pipeline = pipeline.resize({
      width: MAX_EDGE,
      height: MAX_EDGE,
      fit: 'inside',
      withoutEnlargement: true,
    });
  }
  const ext = extname(file).toLowerCase();
  if (ext === '.png') pipeline = pipeline.png({ compressionLevel: 9, palette: tooHeavy });
  else if (ext === '.webp') pipeline = pipeline.webp({ quality: 82 });
  else pipeline = pipeline.jpeg({ quality: 82, mozjpeg: true });

  const out = await pipeline.toBuffer();
  await writeFile(file, out);
  changed++;
  console.log(
    `  optimized ${file.replaceAll('\\', '/')}: ${meta.width}×${meta.height}, ${kb(size)} → ${kb(out.length)}`,
  );
}

console.log(changed ? `✔ ${changed} image(s) optimized.` : '✔ Images already optimized.');
